export const SC2TC_CHARS: Record<string, string> = { ...SC2TC_CHARS_BASE, ...SC2TC_CHARS_EXTRA }

const PHRASE_KEYS = Object.keys(SC2TC_HK_PHRASES).sort((a, b) => b.length - a.length)
/** Cheap bail-out: skip the whole pipeline unless the string holds a convertible char. */
const TRIGGER_RE = new RegExp(
  '[' + Object.keys(SC2TC_CHARS).join('') + PHRASE_KEYS.join('') + ']',
)
const CACHE = new Map<string, string>()
const CACHE_MAX = 4096

/** Convert a simplified / mixed status string to Hong-Kong Traditional. Idempotent. */
export function simplifiedToTraditionalHK(s: string): string {
  if (!s || !TRIGGER_RE.test(s)) return s
  const hit = CACHE.get(s)
  if (hit !== undefined) return hit
  let out = s
  for (const k of PHRASE_KEYS) {
    if (out.includes(k)) out = out.split(k).join(SC2TC_HK_PHRASES[k])
  }
  let chars = ''
  for (const ch of out) chars += SC2TC_CHARS[ch] ?? ch
  if (CACHE.size >= CACHE_MAX) CACHE.clear()
  CACHE.set(s, chars)
  return chars
}
