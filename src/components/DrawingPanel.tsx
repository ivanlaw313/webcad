const projSym = (x: number, yMid: number, h: number, first: boolean) => {
  const R = h * 0.5, r = h * 0.24, tw = h * 1.5, gap = h * 0.35, nh = h * 0.3, wh = h * 0.5
  const tx0 = first ? x : x + 2 * R + gap // 梯形左缘
  const cx = first ? x + tw + gap + R : x + R // 圆心
  const lines: number[][] = [
    [tx0, yMid - nh, tx0 + tw, yMid - wh], [tx0 + tw, yMid - wh, tx0 + tw, yMid + wh],
    [tx0 + tw, yMid + wh, tx0, yMid + nh], [tx0, yMid + nh, tx0, yMid - nh],
  ]
  return { lines, circles: [{ cx, cy: yMid, r: R }, { cx, cy: yMid, r }], w: tw + gap + 2 * R }
}

