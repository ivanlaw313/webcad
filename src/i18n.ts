/** Translate a ribbon tool label (source string) via catalog key when known. */
export function tLabel(label: string, lang: LangInput): string {
  const L = normalizeLang(lang)
  const key = LABEL_TO_KEY[label]
  if (key) return msg(key, L)
  if (L === 'en') return EN_LABEL[label] ?? label
  if (L === 'zh-CN') return ZH_CN_LABEL[label] ?? traditionalToSimplified(label)
  if (L === 'ja') return JA_LABEL[label] ?? EN_LABEL[label] ?? label  // unmigrated → EN CAD term fallback
  return label  // zh-HK: source (TC) as-is
}


/** Ribbon button caption by command id (v1.83 cmd.* catalog). Variant labels via LABEL_TO_KEY. */
export function ribbonCmdLabel(id: string, lang: LangInput, fallbackLabel?: string): string {
  const L = normalizeLang(lang)
  if (fallbackLabel) {
    const mapped = LABEL_TO_KEY[fallbackLabel]
    if (mapped) return msg(mapped, L)
  }
  const key = `cmd.${id}`
  const cat = msg(key, L)
  if (cat !== key) return cat
  const toolKey = `tool.${id}`
  const tool = msg(toolKey, L)
  if (tool !== toolKey) return tool
  return fallbackLabel ? tLabel(fallbackLabel, L) : id
}


/** Translate a ribbon group name (data key or Chinese panel name). */
export function tGroup(name: string, lang: LangInput): string {
  const L = normalizeLang(lang)
  const key = GROUP_TO_KEY[name]
  if (key) return msg(key, L)
  if (L === 'zh-HK') return ZH_GROUP[name] ?? name
  if (L === 'zh-CN') return traditionalToSimplified(ZH_GROUP[name] ?? name)
  if (L === 'en') return name
  // ja: unmapped groups keep English data-key (honest fallback)
  return name
}

