/* Browser acceptance for the deployed Physics Lab.  It checks the real WASM
 * load path and user-visible controls, not just source-level contracts. */
import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const baseURL = (process.argv[2] ?? 'https://cad.neuralworkshk.com').replace(/\/$/, '')
const executablePath = process.env.CHROME_PATH ?? 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe'
const browser = await chromium.launch({ headless: true, executablePath })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const pageErrors = []
  page.on('pageerror', (e) => pageErrors.push(e.message))
  await page.goto(`${baseURL}/?ui-test=1`, { waitUntil: 'networkidle', timeout: 60000 })
  // Build a real SOLID body through the same UI that an operator uses, then
  // freeze it as an assembly component. The lab must accept document geometry,
  // rather than only its internal demo props.
  await page.locator('[data-ribbon-group="CREATE"]').click()
  await page.locator('.panel-menu-item', { hasText: '长方体' }).click()
  const commandDialog = page.locator('[data-testid="command-dialog"]')
  await commandDialog.waitFor({ state: 'visible', timeout: 30000 })
  const dimensions = commandDialog.locator('input[inputmode="decimal"]')
  await dimensions.nth(0).fill('40')
  await dimensions.nth(1).fill('30')
  await dimensions.nth(2).fill('20')
  await page.keyboard.press('Enter')
  await commandDialog.waitFor({ state: 'hidden', timeout: 30000 })
  await page.locator('[data-cmd="newcomp"]').first().click()
  await page.waitForFunction(() => document.querySelectorAll('.tree-row').length > 0)
  await page.locator('.ribbon-tab', { hasText: '實驗室' }).click()
  const trigger = page.locator('[data-cmd="physicslab"]')
  await trigger.waitFor({ state: 'visible', timeout: 30000 })
  await trigger.click()
  const lab = page.locator('.physics-lab')
  await lab.waitFor({ state: 'visible', timeout: 30000 })
  assert.ok(await lab.getByText('環境模擬實驗室').count(), 'Physics Lab title must be visible')
  await lab.getByRole('button', { name: '儲存目前設定' }).click()
  assert.equal(await page.evaluate(() => typeof JSON.parse(localStorage.getItem('webcad.physics-lab.scenario/v1') ?? 'null')?.gravity), 'number')
  const componentToggle = lab.getByRole('checkbox', { name: /將可見元件投入實驗/ })
  assert.equal(await componentToggle.isEnabled(), true, 'a real visible CAD component must be available to inject')
  await componentToggle.check()
  assert.equal(await componentToggle.isChecked(), true)
  const setRange = async (testId, value) => {
    const input = lab.locator(`[data-testid="${testId}"]`)
    await input.evaluate((node, next) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')?.set?.call(node, String(next)); node.dispatchEvent(new Event('input', { bubbles: true })); node.dispatchEvent(new Event('change', { bubbles: true })) }, value)
    assert.equal(await input.inputValue(), String(value))
  }
  // The simulation room itself is user-configurable; the persisted scenario
  // must retain all three collision-boundary dimensions.
  await setRange('physics-room-width', '20')
  await setRange('physics-room-depth', '18')
  await setRange('physics-room-height', '8')
  const windSpeed = lab.locator('[data-testid="physics-wind-speed"]')
  await windSpeed.evaluate((input) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')?.set?.call(input, '12'); input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true })) })
  assert.equal(await windSpeed.inputValue(), '12')
  const windDirection = lab.locator('[data-testid="physics-wind-direction"]')
  await windDirection.selectOption('z+')
  assert.equal(await windDirection.inputValue(), 'z+')
  await setRange('physics-start-x', '2.5')
  await setRange('physics-start-z', '-1.5')
  await setRange('physics-start-vz', '3')
  await setRange('physics-air-density', '0')
  const ballMaterial = lab.locator('[data-testid="physics-ball-material"]')
  await ballMaterial.selectOption('rubber')
  assert.equal(await ballMaterial.inputValue(), 'rubber')
  await lab.getByRole('button', { name: '儲存目前設定' }).click()
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('webcad.physics-lab.scenario/v1') ?? 'null')?.windDirection), 'z+')
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('webcad.physics-lab.scenario/v1') ?? 'null')?.ballMaterial), 'rubber')
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('webcad.physics-lab.scenario/v1') ?? 'null')?.airDensity), 0)
  assert.deepEqual(await page.evaluate(() => { const s = JSON.parse(localStorage.getItem('webcad.physics-lab.scenario/v1') ?? 'null'); return [s?.roomWidth, s?.roomDepth, s?.roomHeight] }), [20, 18, 8])
  assert.deepEqual(await page.evaluate(() => { const s = JSON.parse(localStorage.getItem('webcad.physics-lab.scenario/v1') ?? 'null'); return [s?.startX, s?.startZ, s?.startVz] }), [2.5, -1.5, 3])
  const timeScale = lab.locator('label', { hasText: '模擬速度' }).locator('input')
  await timeScale.evaluate((input) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')?.set?.call(input, '2'); input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true })) })
  assert.equal(await timeScale.inputValue(), '2')
  const armToggle = lab.getByRole('checkbox', { name: /加入三節機械臂示例/ })
  await armToggle.check()
  assert.equal(await armToggle.isChecked(), true)
  const armMotor = lab.locator('label', { hasText: '基座馬達' }).locator('input')
  await armMotor.evaluate((input) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')?.set?.call(input, '30'); input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true })) })
  assert.equal(await armMotor.inputValue(), '30')
  const hingeToggle = lab.getByRole('checkbox', { name: /將 CAD 物件固定到轉軸/ })
  await hingeToggle.check()
  assert.equal(await hingeToggle.isChecked(), true)
  const motor = lab.locator('label', { hasText: '轉軸馬達' }).locator('input')
  await motor.evaluate((input) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')?.set?.call(input, '45'); input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true })) })
  assert.equal(await motor.inputValue(), '45')
  await hingeToggle.uncheck()
  const sliderToggle = lab.getByRole('checkbox', { name: /將 CAD 物件固定到線性滑軌/ })
  await sliderToggle.check()
  assert.equal(await sliderToggle.isChecked(), true)
  const sliderSpeed = lab.locator('label', { hasText: '直線馬達' }).locator('input')
  await sliderSpeed.evaluate((input) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')?.set?.call(input, '1'); input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true })) })
  assert.equal(await sliderSpeed.inputValue(), '1')
  const rampToggle = lab.getByRole('checkbox', { name: /加入固定斜坡/ })
  await rampToggle.check()
  assert.equal(await rampToggle.isChecked(), true)
  const rampAngle = lab.locator('label', { hasText: '斜坡角度' }).locator('input')
  await rampAngle.evaluate((input) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')?.set?.call(input, '12'); input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true })) })
  assert.equal(await rampAngle.inputValue(), '12')
  const obstacles = lab.locator('label', { hasText: '障礙方塊' }).locator('input')
  await obstacles.evaluate((input) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')?.set?.call(input, '4'); input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true })) })
  assert.equal(await obstacles.inputValue(), '4')
  await page.waitForTimeout(350)
  await lab.getByRole('button', { name: /播放/ }).click()
  await page.waitForTimeout(3000)
  // Component telemetry uses the same list styling; the collision history is the final list.
  assert.match(await lab.locator('.physics-lab-events').last().innerText(), /測試球|CAD 物件/, 'a real collision must be reported after play')
  const downloadPromise = page.waitForEvent('download')
  await lab.getByRole('button', { name: '⇩ 報告' }).click()
  const report = await downloadPromise
  assert.match(report.suggestedFilename(), /^webcad-physics-lab-\d+\.json$/)
  assert.equal(pageErrors.length, 0, `page errors: ${pageErrors.join('\n')}`)
  console.log(JSON.stringify({ ok: true, target: baseURL, physicsLab: 'opened-saved-collided-and-exported-report' }))
} finally {
  await browser.close()
}
