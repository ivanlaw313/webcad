const fmtMm = (n: number) => n.toFixed(2).replace(/\.?0+$/, '') // 4.00→"4", 12.50→"12.5", 3.99→"3.99"
const fmtTol = (n: number) => Math.abs(n).toFixed(3).replace(/\.?0+$/, '') // 0.050→"0.05", 0.100→"0.1", 0→"0"
// Tolerance suffix appended to a dimension value. Symmetric (u = −l, nonzero) → " ±0.05"; otherwise the
// signed upper/lower pair " +0.05/−0.02" (− is U+2212; lower keeps its sign, 0 shows as "0"). "" if no tol.
const tolStr = (t?: Tol): string => {
  if (!t) return ''
  if (Math.abs(t.u + t.l) < 1e-9 && Math.abs(t.u) > 1e-9) return ' ±' + fmtTol(t.u)
  const sgn = (n: number) => (n > 1e-9 ? '+' : n < -1e-9 ? '−' : '') + fmtTol(n)
  return ' ' + sgn(t.u) + '/' + sgn(t.l)
}
