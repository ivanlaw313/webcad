// Store+kernel timing benchmark (node, real OCCT): node --experimental-strip-types --import ./tests/register-resolver.mjs scripts/perf-bench-store.mjs
import { register, createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { performance } from 'node:perf_hooks'
globalThis.require = createRequire(import.meta.url)
globalThis.__dirname = fileURLToPath(new URL('../tests/', import.meta.url))
register('../tests/native-car-loader.mjs', import.meta.url)
await import('../src/worker/cad.worker.ts')
await globalThis.__wheelWorker.ready()
const { useApp, buildProjectPayload } = await import('../src/store.ts')
const g = () => useApp.getState()
let sets = 0; useApp.subscribe(() => sets++)
const T = async (label, fn) => { const s0 = sets; const t = performance.now(); const r = await fn(); console.log(label.padEnd(28), (performance.now() - t).toFixed(1).padStart(9), 'ms  sets=' + (sets - s0), '|', String(g().status).slice(0, 70)); return r }
useApp.setState(useApp.getInitialState(), true)
await T('plate extrude', async () => { g().startSketch(); g().chooseSketchPlane('XY'); useApp.setState({ sketchShape: { type: 'rect', a: [-25, -20], b: [25, 20] }, sketchProfiles: [], skCons: [], extrudeHeight: 10, sketchOp: 'new' }); await g().extrudeSketch() })
console.log('mesh verts', g().bodyMesh?.vertices.length, 'tris', g().bodyMesh?.triangles.length)
await T('startSketchOnFace top', () => g().startSketchOnFace([0, 10, 0], [0, 0, 1]))
console.log('refGeo segs', g().skRefGeo?.segs?.length, 'mode', g().mode)
await T('projectRefToSketch', () => g().projectRefToSketch())
console.log('shapes', g().sketchProfiles.length + (g().sketchShape ? 1 : 0), 'pts', [...g().sketchProfiles, g().sketchShape].filter(Boolean).map(s => s.pts?.length))
await T('finishSketch(commit)', () => g().commitStandaloneSketch())
console.log('features', g().features.map(f => f.type).join(','))
// third feature: hole-ish cut via another sketch
await T('2nd sketch extrude', async () => { g().startSketch(); g().chooseSketchPlane('XY'); useApp.setState({ sketchBaseZ: 10, sketchShape: { type: 'circle', c: [0, 0], r: 5 }, sketchProfiles: [], skCons: [], extrudeHeight: 5, sketchOp: 'new' }); await g().extrudeSketch() })
console.log('features', g().features.map(f => f.type).join(','), 'undo', g().undoStack.length)
for (let i = 0; i < 3; i++) await T('payload+stringify', () => JSON.stringify(buildProjectPayload(g())).length)
console.log('payload bytes', JSON.stringify(buildProjectPayload(g())).length)
await T('undo', () => g().undo())
await T('redo', () => g().redo())
const last = g().features.at(-1)
await T('moveFeature up', () => g().moveFeature(last.id, -1))
await T('moveFeature down', () => g().moveFeature(last.id, 1))
const sk = g().features.find(f => f.type === 'sketch')
await T('removeFeature sketch', () => g().removeFeature(sk.id))
await T('undo', () => g().undo())
await T('gotoStep 1', () => g().gotoStep(1))
await T('gotoStep end', () => g().gotoStep(g().features.length))
console.log('heap MB', (process.memoryUsage().heapUsed / 1e6).toFixed(1))
process.exit(0)
